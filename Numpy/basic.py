import numpy as np

# 1D array
arr1 = np.array([1, 2, 3, 4, 5])
print("1D array:", arr1)

# 2D array (matrix)
arr2 = np.array([[1, 2, 3], [4, 5, 6]])
print("2D array:\n", arr2)

# Array of zeros and ones
zeros = np.zeros((2, 3))   # row & columns
ones = np.ones((3, 3))
print("Zeros:\n", zeros)
print("Ones:\n", ones)


